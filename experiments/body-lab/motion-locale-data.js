function structureName(text, slot) {
  const direct = dataStrings[text]?.[slot] ?? muscleNames[text]?.[slot];
  if (direct) return direct;

  const rib = /^第\s*(\d+)\s*肋(?: · ([XYZ]) 轴)?$/.exec(text);
  if (rib) {
    const [, number, axis] = rib;
    if (slot === 1) return `第${number}肋骨${axis ? " · " + axis + "軸" : ""}`;
    return `Rib ${number}${axis ? " · " + axis + " axis" : ""}`;
  }

  const vertebra = /^(胸椎|腰椎)(\d+)$/.exec(text);
  if (vertebra) {
    const [, region, number] = vertebra;
    return slot === 0
      ? `${region === "胸椎" ? "Thoracic" : "Lumbar"} vertebra ${number}`
      : `第${number}${region === "胸椎" ? "胸椎" : "腰椎"}`;
  }

  const digit = /^(拇指|食指|中指|环指|无名指|小指)(近节|中节|末节|腕掌|掌指|指间|近端指间|远端指间)(?: · (屈伸|外展))?$/.exec(text);
  if (digit) {
    const [, finger, segment, movement] = digit;
    const motion = movement ? " · " + dataStrings[movement][slot] : "";
    if (slot === 1) return fingers[finger][1] + fingerSegments[segment][1] + motion;
    return `${fingers[finger][0]} ${fingerSegments[segment][0]}${motion}`;
  }

  const spine = /^(头颈|腹部|[TLS]\d+–[TLS]\d+) · (屈伸|侧屈|旋转)$/.exec(text);
  if (spine) return `${dataStrings[spine[1]]?.[slot] ?? spine[1]} · ${dataStrings[spine[2]][slot]}`;

  const bundle = /^(臀大肌|臀中肌|臀小肌) · 肌束 (\d+)$/.exec(text);
  if (bundle) return `${muscleNames[bundle[1]][slot]} · ${slot === 0 ? "Bundle " : "筋束"}${bundle[2]}`;
}

// Unknown text deliberately falls through to the caller, including native model IDs.
export function translateAnatomy(text, lang) {
  if (typeof text !== "string" || (lang !== "en" && lang !== "ja")) return undefined;
  const slot = lang === "en" ? 0 : 1;
  const direct = dataStrings[text]?.[slot];
  if (direct) return direct;
  const side = /^([左右])侧?(.+)$/.exec(text);
  if (!side) return structureName(text, slot);
  const name = structureName(side[2], slot);
  if (!name) return undefined;
  if (slot === 1) return side[1] + name;
  const prefix = side[1] === "左" ? "Left" : "Right";
  // Keep proper names and anatomical segment codes capitalized.
  const label = /^(?:Achilles|[TLS]\d)/.test(name) ? name : name[0].toLowerCase() + name.slice(1);
  return prefix + " " + label;
}
